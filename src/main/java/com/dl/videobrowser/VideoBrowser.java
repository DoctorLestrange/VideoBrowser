    private void populateTable() {
        if (extractedVideoData.isEmpty()) {
            mainTable.setModel(new DefaultTableModel());
            return;
        }
        boolean duration = durationCB.isSelected();
        boolean size = sizeCB.isSelected();
        boolean codec = codecCB.isSelected();
        boolean resolution = resCB.isSelected();
        boolean bitrate = bitrateCB.isSelected();
        boolean descending = desRB.isSelected();
        String sortBy = sortCB.getSelectedItem() != null ? sortCB.getSelectedItem().toString() : "Name";

        TableModel tableModel = createVideoTableModel(sortBy, descending, duration, size, codec, resolution, bitrate);
        mainTable.setModel(tableModel);

        TableRowSorter<TableModel> sorter = new TableRowSorter<>(tableModel);
        for (int i = 0; i < tableModel.getColumnCount(); i++) {
            String colName = tableModel.getColumnName(i);
            switch (colName) {
                case "File Name", "Codec" ->
                    sorter.setComparator(i, String.CASE_INSENSITIVE_ORDER);
                case "Duration" ->
                    sorter.setComparator(i, (o1, o2) -> Long.compare(parseDurationToSeconds(o1), parseDurationToSeconds(o2)));
                case "Size" ->
                    sorter.setComparator(i, (o1, o2) -> Long.compare(parseSizeStringToKb(o1), parseSizeStringToKb(o2)));
                case "Bitrate" ->
                    sorter.setComparator(i, (o1, o2) -> Long.compare(parseBitrateStringToKbps(o1), parseBitrateStringToKbps(o2)));
                case "Resolution" ->
                    sorter.setComparator(i, (o1, o2) -> Long.compare(calculatePixels(o1 != null ? o1.toString() : ""), calculatePixels(o2 != null ? o2.toString() : "")));
            }
        }
        mainTable.setRowSorter(sorter);

        filter();
        resizeColumnWidth();
    }

    private void filter() {
        if (mainTable.getRowSorter() == null) {
            return;
        }
        @SuppressWarnings("unchecked")
        TableRowSorter<TableModel> sorter = (TableRowSorter<TableModel>) mainTable.getRowSorter();

        String text = searchTF.getText().trim();
        if (text.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            final String lower = text.toLowerCase();
            sorter.setRowFilter(new RowFilter<TableModel, Integer>() {
                @Override
                public boolean include(Entry<? extends TableModel, ? extends Integer> entry) {
                    int count = entry.getValueCount();
                    for (int i = 0; i < count; i++) {
                        Object val = entry.getValue(i);
                        if (val != null && val.toString().toLowerCase().contains(lower)) {
                            return true;
                        }
                    }
                    return false;
                }
            });
        }
    }

