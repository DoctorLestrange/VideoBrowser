    private void openSelectedFile() {
        int selectedRow = mainTable.getSelectedRow();
        if (selectedRow == -1) {
            return;
        }
        int modelRow = mainTable.convertRowIndexToModel(selectedRow);
        String fileName = (String) mainTable.getModel().getValueAt(modelRow, 0);
        String fullPath = resolveFilePath(fileName);

        if (fullPath == null || fullPath.isEmpty()) {
            log("Error: Cannot open file - path is unknown (data may have been loaded from JSON).");
            JOptionPane.showMessageDialog(this, "The file path is unknown. If this data was imported from JSON, the original file path was not saved.", "File Not Found", JOptionPane.WARNING_MESSAGE);
            return;
        }

        File file = new File(fullPath);
        if (!file.exists() || !file.isFile()) {
            log("Error: File does not exist: " + file.getAbsolutePath());
            JOptionPane.showMessageDialog(this, "File does not exist:\n" + file.getAbsolutePath(), "File Not Found", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            if (Desktop.isDesktopSupported() && Desktop.getDesktop().isSupported(Desktop.Action.OPEN)) {
                Desktop.getDesktop().open(file);
                log("Opening file: " + fileName);
            } else if (SystemInfo.isLinux) {
                new ProcessBuilder("xdg-open", file.getAbsolutePath()).start();
                log("Opening file with xdg-open: " + fileName);
            } else {
                throw new UnsupportedOperationException("Desktop open action is not supported on this platform.");
            }
        } catch (Exception ex) {
            log("Failed to open file: " + ex.getMessage());
            showErrorMessage(ex);
        }
    }

    /**
     * Checks if ffprobe is accessible via system PATH and caches the resolved path.
     */
    private void checkFFprobeAvailability() {
        try {
            if (SystemInfo.isWindows) {
                try {
                    Process whereProc = new ProcessBuilder("where", "ffprobe").start();
                    try (BufferedReader reader = new BufferedReader(new InputStreamReader(whereProc.getInputStream(), StandardCharsets.UTF_8))) {
                        String line = reader.readLine();
                        if (line != null && !line.trim().isEmpty() && new File(line.trim()).exists()) {
                            resolvedFFprobePath = line.trim();
                        }
                    }
                    whereProc.waitFor(2, TimeUnit.SECONDS);
                } catch (Exception ignored) {
                }
            }

            Process process = new ProcessBuilder(resolvedFFprobePath, "-version").start();
            boolean finished = process.waitFor(3, TimeUnit.SECONDS);
            if (finished && process.exitValue() == 0) {
                isFFprobeAvailable = true;
                return;
            }
        } catch (Exception ignored) {
        }

        isFFprobeAvailable = false;
        log("Notice: FFprobe was not found on system PATH. JSON viewer mode active.");

        SwingUtilities.invokeLater(this::promptFFprobeDownload);
    }

    private void promptFFprobeDownload() {
        int opt = JOptionPane.showOptionDialog(
                this,
                "FFprobe is required to extract metadata from video files, but was not found on your system PATH.\n\n"
                + "You can still open, view, sort, search, and export JSON files.\n"
                + "However, extracting new video metadata from folders requires FFmpeg/FFprobe.\n\n"
                + "Would you like to open the FFmpeg download page?",
                "FFprobe Missing",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE,
                null,
                new String[]{"Download FFmpeg", "Continue in Viewer Mode"},
                "Continue in Viewer Mode"
        );
        if (opt == 0) {
            try {
                if (Desktop.isDesktopSupported()) {
                    Desktop.getDesktop().browse(new URI("https://ffmpeg.org/download.html"));
                }
            } catch (Exception ex) {
                log("Failed to open browser: " + ex.getMessage());
            }
        }
    }

