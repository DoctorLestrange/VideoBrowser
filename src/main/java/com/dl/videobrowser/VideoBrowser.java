    private void loadMIActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loadMIActionPerformed
        try {
            JFileChooser fileChooser = new JFileChooser();
            fileChooser.setDialogTitle("Load Video Metadata JSON");
            fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("JSON Files (*.json)", "json"));
            int result = fileChooser.showOpenDialog(this);
            if (result == JFileChooser.APPROVE_OPTION) {
                File jsonFile = fileChooser.getSelectedFile();
                ObjectMapper mapper = new ObjectMapper();
                mapper.configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
                mapper.configure(DeserializationFeature.ACCEPT_SINGLE_VALUE_AS_ARRAY, true);

                List<VideoInfo> data = mapper.readValue(jsonFile, new TypeReference<List<VideoInfo>>() {
                });
                if (data == null || data.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "The selected JSON file contains no video records.", "Empty Dataset", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                synchronized (extractedVideoData) {
                    extractedVideoData.clear();
                    extractedVideoData.addAll(data);
                }

                for (VideoInfo info : data) {
                    if (info.filePath != null && !info.filePath.isEmpty()) {
                        File parentFile = new File(info.filePath).getParentFile();
                        if (parentFile != null && parentFile.exists()) {
                            validFolderPath = parentFile.getAbsolutePath();
                            pathTF.setText(validFolderPath);
                            break;
                        }
                    }
                }

                populateTable();
                log("Data from JSON loaded successfully (" + data.size() + " items).");
            }
        } catch (HeadlessException | IOException e) {
            showErrorMessage(e);
        }
    }//GEN-LAST:event_loadMIActionPerformed

