    private void log(String message) {
        final String newMessage = getDateTime() + "    " + message;

        SwingUtilities.invokeLater(() -> {
            ListModel<String> currentModel = logList.getModel();
            DefaultListModel<String> model;

            if (currentModel instanceof DefaultListModel) {
                model = (DefaultListModel<String>) currentModel;
            } else {
                model = new DefaultListModel<>();
                for (int i = 0; i < currentModel.getSize(); i++) {
                    model.addElement(currentModel.getElementAt(i));
                }
                logList.setModel(model);
            }

            model.addElement(newMessage);

            // Cap logs at 500 lines to avoid excessive memory retention
            if (model.getSize() > 500) {
                model.remove(0);
            }

            int lastIndex = model.getSize() - 1;
            if (lastIndex >= 0) {
                logList.ensureIndexIsVisible(lastIndex);
            }
        });
    }

