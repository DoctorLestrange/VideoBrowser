    private void exportMIActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_exportMIActionPerformed
        if (extractedVideoData.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No video data available to export!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Save Exported Data as JSON");

        javax.swing.filechooser.FileNameExtensionFilter filter
                = new javax.swing.filechooser.FileNameExtensionFilter("JSON Files (*.json)", "json");
        fileChooser.setFileFilter(filter);
        fileChooser.setAcceptAllFileFilterUsed(false);
        fileChooser.setSelectedFile(new File("video_metadata_export.json"));

        int userSelection = fileChooser.showSaveDialog(this);

        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File fileToSave = fileChooser.getSelectedFile();

            String filePath = fileToSave.getAbsolutePath();
            if (!filePath.toLowerCase().endsWith(".json")) {
                fileToSave = new File(filePath + ".json");
            }

            if (fileToSave.exists()) {
                int confirm = JOptionPane.showConfirmDialog(
                        this,
                        "The file '" + fileToSave.getName() + "' already exists.\nDo you want to overwrite it?",
                        "Confirm Overwrite",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.WARNING_MESSAGE
                );
                if (confirm != JOptionPane.YES_OPTION) {
                    return;
                }
            }

            exportDataToJson(fileToSave);
        }
    }//GEN-LAST:event_exportMIActionPerformed

