    private void resizeColumnWidth() {
        final TableColumnModel columnModel = mainTable.getColumnModel();
        int rowCount = Math.min(mainTable.getRowCount(), 150);
        for (int column = 0; column < mainTable.getColumnCount(); column++) {
            int width = 70;
            for (int row = 0; row < rowCount; row++) {
                javax.swing.table.TableCellRenderer renderer = mainTable.getCellRenderer(row, column);
                java.awt.Component comp = mainTable.prepareRenderer(renderer, row, column);
                width = Math.max(comp.getPreferredSize().width + 16, width);
            }
            javax.swing.table.JTableHeader header = mainTable.getTableHeader();
            if (header != null) {
                javax.swing.table.TableCellRenderer headerRenderer = header.getDefaultRenderer();
                java.awt.Component headerComp = headerRenderer.getTableCellRendererComponent(mainTable,
                        columnModel.getColumn(column).getHeaderValue(), false, false, 0, column);
                width = Math.max(width, headerComp.getPreferredSize().width + 24);
            }

            columnModel.getColumn(column).setPreferredWidth(width);
        }
    }

    private TableModel createVideoTableModel(String sortBy, boolean descending, boolean showDuration, boolean showSize, boolean showCodec,
            boolean showResolution, boolean showBitrate) {

        List<VideoInfo> sortedList;
        synchronized (extractedVideoData) {
            sortedList = new ArrayList<>(extractedVideoData);
        }

        Comparator<VideoInfo> comparator = switch (sortBy.toLowerCase()) {
            case "name" ->
                Comparator.comparing(o -> o.fileName != null ? o.fileName.toLowerCase() : "");
            case "duration" ->
                Comparator.comparingDouble(o -> o.durationSeconds);
            case "size" ->
                Comparator.comparingLong(o -> o.fileSize);
            case "codec" ->
                Comparator.comparing(o -> o.videoCodec != null ? o.videoCodec.toLowerCase() : "");
            case "bitrate" ->
                Comparator.comparingLong(o -> o.bitRate);
            case "resolution" ->
                (o1, o2) -> Long.compare(calculatePixels(o1.resolution), calculatePixels(o2.resolution));
            default ->
                Comparator.comparing(o -> o.fileName != null ? o.fileName.toLowerCase() : "");
        };

        if (descending) {
            comparator = comparator.reversed();
        }
        sortedList.sort(comparator);

        List<String> columnNames = new ArrayList<>();
        columnNames.add("File Name");
        if (showDuration) {
            columnNames.add("Duration");
        }
        if (showSize) {
            columnNames.add("Size");
        }
        if (showCodec) {
            columnNames.add("Codec");
        }
        if (showResolution) {
            columnNames.add("Resolution");
        }
        if (showBitrate) {
            columnNames.add("Bitrate");
        }

        Object[][] data = new Object[sortedList.size()][columnNames.size()];

        for (int i = 0; i < sortedList.size(); i++) {
            VideoInfo info = sortedList.get(i);
            int colIndex = 0;

            data[i][colIndex++] = info.fileName != null ? info.fileName : "";

            if (showDuration) {
                data[i][colIndex++] = formatDuration(info.durationSeconds);
            }
            if (showSize) {
                long sizeInKB = info.fileSize / 1024;
                data[i][colIndex++] = String.format("%,d KB", sizeInKB);
            }
            if (showCodec) {
                data[i][colIndex++] = info.videoCodec != null ? info.videoCodec : "Unknown";
            }
            if (showResolution) {
                data[i][colIndex++] = info.resolution != null ? info.resolution : "N/A";
            }
            if (showBitrate) {
                data[i][colIndex++] = String.format("%,d kbps", info.bitRate / 1000);
            }
        }

        String[] columnsArray = columnNames.toArray(String[]::new);

        return new DefaultTableModel(data, columnsArray) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    private long parseDurationToSeconds(Object obj) {
        if (obj == null) {
            return 0;
        }
        String s = obj.toString().trim();
        String[] parts = s.split(":");
        if (parts.length == 3) {
            try {
                long h = Long.parseLong(parts[0]);
                long m = Long.parseLong(parts[1]);
                long sec = Long.parseLong(parts[2]);
                return h * 3600 + m * 60 + sec;
            } catch (NumberFormatException ignored) {
            }
        }
        return 0;
    }

    private long parseSizeStringToKb(Object obj) {
        if (obj == null) {
            return 0;
        }
        String s = obj.toString().replaceAll("[^0-9]", "");
        if (s.isEmpty()) {
            return 0;
        }
        try {
            return Long.parseLong(s);
        } catch (NumberFormatException ignored) {
            return 0;
        }
    }

    private long parseBitrateStringToKbps(Object obj) {
        if (obj == null) {
            return 0;
        }
        String s = obj.toString().replaceAll("[^0-9]", "");
        if (s.isEmpty()) {
            return 0;
        }
        try {
            return Long.parseLong(s);
        } catch (NumberFormatException ignored) {
            return 0;
        }
    }

    private long calculatePixels(String res) {
        if (res == null || !res.contains("x")) {
            return 0;
        }
        try {
            String[] parts = res.trim().split("x");
            if (parts.length == 2) {
                long w = Long.parseLong(parts[0]);
                long h = Long.parseLong(parts[1]);
                return w * h;
            }
        } catch (NumberFormatException ignored) {
        }
        return 0;
    }

    private String formatDuration(double totalSeconds) {
        long sec = Math.round(totalSeconds);
        long hours = sec / 3600;
        long remainder = sec % 3600;
        long minutes = remainder / 60;
        long seconds = remainder % 60;
        return String.format("%02d:%02d:%02d", hours, minutes, seconds);
    }

    /**
     * Extracts metadata for all video files in the specified directory.
     * Fully asynchronous with parallel worker threads; never freezes the UI.
     *
     * @param directoryPath The path to the folder containing videos.
     */
    private void extractVideoDetails(String directoryPath) {
        if (isExtracting) {
            log("Extraction is already in progress. Please wait...");
            return;
        }

        if (directoryPath == null || directoryPath.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select or enter a directory path.", "No Directory Specified", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String trimmed = directoryPath.trim();
        if ((trimmed.startsWith("\"") && trimmed.endsWith("\"")) || (trimmed.startsWith("'") && trimmed.endsWith("'"))) {
            trimmed = trimmed.substring(1, trimmed.length() - 1).trim();
        }
        final String cleanPath = trimmed;

        if (!isFFprobeAvailable) {
            promptFFprobeDownload();
            return;
        }

        // Set UI to loading state immediately on EDT (ZERO UI freeze)
        isExtracting = true;
        loadButton.setEnabled(false);
        pathTF.setEnabled(false);
        browseButton.setEnabled(false);
        progressBar.setVisible(true);
        progressBar.setIndeterminate(true);
        progressBar.setStringPainted(true);
        progressBar.setString("Scanning files on disk...");
        log("Scanning directory: " + cleanPath);

        // Dispatch directory scanning and extraction entirely to background worker
        new Thread(() -> {
            try {
                File folder = new File(cleanPath);
                if (!folder.exists() || !folder.isDirectory()) {
                    SwingUtilities.invokeLater(() -> {
                        JOptionPane.showMessageDialog(this, "The specified directory does not exist or is not a folder:\n" + cleanPath, "Invalid Directory", JOptionPane.ERROR_MESSAGE);
                        log("Error: Invalid directory path: " + cleanPath);
                    });
                    return;
                }

                // Ultra-fast in-memory extension pre-filter: avoids hitting disk attributes for non-video files!
                final String[] videoExtensions = new String[]{"mp4", "mkv", "avi", "mov", "flv", "wmv", "webm", "m4v", "ts", "m2ts", "vob", "ogv", "3gp", "mpg", "mpeg"};
                final java.util.Set<String> validExts = new java.util.HashSet<>(Arrays.asList(videoExtensions));

                File[] videoFiles = folder.listFiles((File dir, String name) -> {
                    int lastDot = name.lastIndexOf('.');
                    if (lastDot <= 0) {
                        return false;
                    }
                    String ext = name.substring(lastDot + 1).toLowerCase();
                    if (!validExts.contains(ext)) {
                        return false;
                    }
                    File f = new File(dir, name);
                    return f.isFile() && !f.isHidden();
                });

                if (videoFiles == null || videoFiles.length == 0) {
                    SwingUtilities.invokeLater(() -> {
                        JOptionPane.showMessageDialog(this, "No video files found in the specified directory.", "No Videos Found", JOptionPane.INFORMATION_MESSAGE);
                        log("No video files found in: " + folder.getAbsolutePath());
                    });
                    return;
                }

                Arrays.sort(videoFiles, Comparator.comparing(File::getName, String.CASE_INSENSITIVE_ORDER));
                final int totalFiles = videoFiles.length;
                validFolderPath = folder.getAbsolutePath();

                SwingUtilities.invokeLater(() -> {
                    progressBar.setIndeterminate(false);
                    progressBar.setMinimum(0);
                    progressBar.setMaximum(totalFiles);
                    progressBar.setValue(0);
                    progressBar.setString("0 / " + totalFiles);
                    log("Found " + totalFiles + " video file(s). Extracting metadata...");
                });

                // Bounded extraction pool (2 workers) prevents mechanical HDD head thrashing
                int poolSize = 2;
                ExecutorService extractionPool = Executors.newFixedThreadPool(poolSize);
                List<VideoInfo> extractedLocal = Collections.synchronizedList(new ArrayList<>());
                AtomicInteger completedCount = new AtomicInteger(0);

                List<Future<?>> tasks = new ArrayList<>();
                for (File file : videoFiles) {
                    tasks.add(extractionPool.submit(() -> {
                        VideoInfo info = extractSingleVideo(file);
                        if (info != null) {
                            extractedLocal.add(info);
                        }
                        int current = completedCount.incrementAndGet();
                        SwingUtilities.invokeLater(() -> {
                            progressBar.setValue(current);
                            progressBar.setString(current + " / " + totalFiles);
                        });
                    }));
                }

                for (Future<?> task : tasks) {
                    try {
                        task.get();
                    } catch (Exception ignored) {
                    }
                }
                extractionPool.shutdown();

                // Sort extracted results in consistent filename order
                synchronized (extractedLocal) {
                    extractedLocal.sort(Comparator.comparing(o -> o.fileName != null ? o.fileName.toLowerCase() : ""));
                }

                SwingUtilities.invokeLater(() -> {
                    if (!extractedLocal.isEmpty()) {
                        synchronized (extractedVideoData) {
                            extractedVideoData.clear();
                            extractedVideoData.addAll(extractedLocal);
                        }
                        populateTable();
                        log("Extraction complete. Successfully loaded " + extractedLocal.size() + " of " + totalFiles + " video(s).");
                    } else {
                        log("No video metadata could be extracted from selected directory.");
                        JOptionPane.showMessageDialog(this, "Could not extract metadata from any video files.", "Extraction Notice", JOptionPane.WARNING_MESSAGE);
                    }
                });

            } finally {
                SwingUtilities.invokeLater(() -> {
                    isExtracting = false;
                    loadButton.setEnabled(true);
                    pathTF.setEnabled(true);
                    browseButton.setEnabled(true);
                    progressBar.setIndeterminate(false);
                    progressBar.setStringPainted(false);
                });
            }
        }, "VideoExtractionDispatcher").start();
    }

    /**
     * Extracts metadata for a single video file using ffprobe.
     * Includes automatic retry with a generous 35-second timeout to handle cold disk spin-ups.
     */
    private VideoInfo extractSingleVideo(File file) {
        VideoInfo info = executeProbe(file, 35);
        if (info == null) {
            // Retry once in case drive was waking up from sleep
            info = executeProbe(file, 35);
        }
        if (info == null) {
            info = new VideoInfo();
            info.fileName = file.getName();
            info.filePath = file.getAbsolutePath();
            info.fileSize = file.length();
        }
        return info;
    }

    private VideoInfo executeProbe(File file, int timeoutSeconds) {
        VideoInfo info = new VideoInfo();
        info.fileName = file.getName();
        info.filePath = file.getAbsolutePath();
        info.fileSize = file.length();

        try {
            ProcessBuilder pb = new ProcessBuilder(
                    resolvedFFprobePath,
                    "-v", "error",
                    "-threads", "0",
                    "-select_streams", "v:0",
                    "-show_entries", "stream=width,height,codec_name,bit_rate:format=duration,bit_rate",
                    "-of", "json",
                    file.getAbsolutePath()
            );
            pb.redirectError(ProcessBuilder.Redirect.DISCARD);

            Process process = pb.start();

            byte[] jsonBytes = null;
            try (var in = process.getInputStream()) {
                Future<byte[]> readFuture = CompletableFuture.supplyAsync(() -> {
                    try {
                        return in.readAllBytes();
                    } catch (IOException e) {
                        return new byte[0];
                    }
                });

                try {
                    jsonBytes = readFuture.get(timeoutSeconds, TimeUnit.SECONDS);
                    process.waitFor(2, TimeUnit.SECONDS);
                } catch (TimeoutException te) {
                    process.destroyForcibly();
                    readFuture.cancel(true);
                    log("Extraction timed out for: " + file.getName() + " (retrying or slow disk)");
                    return null;
                }
            }

            if (jsonBytes != null && jsonBytes.length > 0) {
                ObjectMapper mapper = new ObjectMapper();
                mapper.configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
                JsonNode rootNode = mapper.readTree(jsonBytes);

                JsonNode formatNode = rootNode.path("format");
                if (!formatNode.isMissingNode()) {
                    info.durationSeconds = formatNode.path("duration").asDouble(0.0);
                    info.bitRate = formatNode.path("bit_rate").asLong(0);
                }

                JsonNode streamsNode = rootNode.path("streams");
                if (streamsNode.isArray() && streamsNode.size() > 0) {
                    JsonNode videoStream = streamsNode.get(0);
                    int width = videoStream.path("width").asInt(0);
                    int height = videoStream.path("height").asInt(0);
                    if (width > 0 && height > 0) {
                        info.resolution = width + "x" + height;
                    }
                    String codec = videoStream.path("codec_name").asText("");
                    if (!codec.isEmpty()) {
                        info.videoCodec = codec;
                    }
                    long streamBitrate = videoStream.path("bit_rate").asLong(0);
                    if (streamBitrate > 0) {
                        info.bitRate = streamBitrate;
                    }
                }

                // Fallback: check stream duration if container duration is missing
                if (info.durationSeconds == 0.0 && streamsNode.isArray() && streamsNode.size() > 0) {
                    info.durationSeconds = streamsNode.get(0).path("duration").asDouble(0.0);
                }

                // Estimate overall bitrate if container/stream didn't provide one
                if (info.bitRate == 0 && info.durationSeconds > 0 && info.fileSize > 0) {
                    info.bitRate = Math.round((info.fileSize * 8.0) / info.durationSeconds);
                }
            }
            return info;
        } catch (Exception e) {
            log("Failed to extract info for: " + file.getName() + " (" + e.getMessage() + ")");
            return null;
        }
    }

